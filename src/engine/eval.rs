const PSTS: [&[i32; 64]; 6] = [
    &PST_PAWN, &PST_KNIGHT, &PST_BISHOP, &PST_ROOK, &PST_QUEEN, &PST_KING,
];

fn pst(piece: Piece, sq: u8, color: Color) -> i32 {
    let idx = match color {
        Color::White => sq as usize,
        Color::Black => (sq ^ 56) as usize,
    };
    PSTS[piece as usize][idx]
}

pub fn evaluate(pos: &Position) -> i32 {
    let mut score = 0i32;
    for piece in [Piece::Pawn, Piece::Knight, Piece::Bishop, Piece::Rook, Piece::Queen, Piece::King] {
        for color in [Color::White, Color::Black] {
            let mut bb = pos.piece_bb(color, piece);
            let sign = if color == Color::White { 1 } else { -1 };
            for sq in bb {
                score += sign * (MATERIAL[piece as usize] + pst(piece, sq, color));
            }
        }
    }
    if pos.side_to_move == Color::White { score } else { -score }
}